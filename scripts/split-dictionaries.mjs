#!/usr/bin/env node
// One language per download.
//
// src/i18n/dictionaries.js holds English, French and Portuguese in one 1.9 MB
// file, and LanguageProvider imported all of it, so every first visit fetched
// a 621 KB (gzipped) script before the page could do anything: 3.8 seconds on
// v-ent.co on 28 September 2026, with the first API call leaving at 5.2 s.
// Somebody reading English never needs the other two.
//
// dictionaries.js stays the one place strings are written (five tools edit it
// as text). This writes src/i18n/generated/<code>.js from it, one module per
// language, and the browser loads only English plus the reader's own.
//
// A French or Portuguese page then carried its whole table INSIDE its HTML:
// 715 KB of the 783 KB /fr/tournaments, about 200 KB gzipped, on every full
// page load (inbox 454, 13 October 2026). So each non-English table is also
// written to public/i18n/<code>.<hash>.js, a script the browser caches for a
// year because its name changes whenever a word does, and the page names it
// instead of carrying it. generated/scripts.js says which file is current.
//
//   node scripts/split-dictionaries.mjs            write the files
//   node scripts/split-dictionaries.mjs --check    fail if they are stale
//   node scripts/split-dictionaries.mjs --self-test

import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(HERE, '..');
const SOURCE = path.join(ROOT, 'src', 'i18n', 'dictionaries.js');
const OUT = path.join(ROOT, 'src', 'i18n', 'generated');
const PUBLIC_OUT = path.join(ROOT, 'public', 'i18n');

const HEADER = '// Generated by scripts/split-dictionaries.mjs from src/i18n/dictionaries.js.\n'
  + '// Do not edit: change dictionaries.js and run the script (predev and prebuild do).\n';

// One entry per line, like the source: readable diffs, and line-based checkers
// (check-pricing reads copy line by line) see the same lines they see there.
export function render(dictionaries, languages) {
  const files = {};
  for (const { code } of languages) {
    files[`${code}.js`] = `${HEADER}const table = ${JSON.stringify(dictionaries[code], null, 1)};\nexport default table;\n`;
  }
  files['languages.js'] = `${HEADER}export const LANGUAGES = ${JSON.stringify(languages, null, 2)};\n`;
  const scripts = {};
  for (const name of Object.keys(renderPublic(dictionaries, languages))) {
    scripts[name.split('.')[0]] = `/i18n/${name}`;
  }
  files['scripts.js'] = `${HEADER}export const DICT_SCRIPTS = ${JSON.stringify(scripts, null, 2)};\n`;
  return files;
}

/**
 * The non-English tables as scripts a page loads before it hydrates, named by
 * their content so a cached copy is never out of date. One line: nobody reads
 * these, and every byte is downloaded.
 */
export function renderPublic(dictionaries, languages) {
  const files = {};
  for (const { code } of languages) {
    if (code === 'en') continue;
    const body = `self.__VENT_I18N__=Object.assign(self.__VENT_I18N__||{},${JSON.stringify({ [code]: dictionaries[code] })});\n`;
    const hash = crypto.createHash('sha256').update(body).digest('hex').slice(0, 10);
    files[`${code}.${hash}.js`] = body;
  }
  return files;
}

/** Hashed files in public/i18n that no current table names. */
function leftovers(publicFiles, dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir).filter((n) => n.endsWith('.js') && !(n in publicFiles));
}

async function load(file) {
  // A fresh URL each time, so --check after an edit reads the edit.
  const url = `${pathToFileURL(file).href}?t=${Date.now()}`;
  const mod = await import(url);
  return { dictionaries: mod.dictionaries, languages: mod.LANGUAGES };
}

function stale(files, dir) {
  const out = [];
  for (const [name, body] of Object.entries(files)) {
    const target = path.join(dir, name);
    // Line endings aside: git checks these out with CRLF on this machine.
    const have = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : null;
    if (have !== body) out.push(name);
  }
  return out;
}

function selfTest() {
  const tmp = fs.mkdtempSync(path.join(ROOT, '.split-selftest-'));
  const langs = [{ code: 'en' }, { code: 'fr' }];
  const dicts = { en: { 'a.b': 'Hello' }, fr: { 'a.b': 'Bonjour' } };
  let failed = 0;
  const check = (name, ok) => { if (!ok) failed += 1; console.log(`${ok ? 'ok  ' : 'FAIL'} ${name}`); };
  const files = render(dicts, langs);
  check('one file per language plus the list', Object.keys(files).sort().join(',') === 'en.js,fr.js,languages.js,scripts.js');
  check('English file holds no French', !files['en.js'].includes('Bonjour'));
  check('nothing written reads as stale-free', stale(files, tmp).length === 4);
  for (const [n, b] of Object.entries(files)) fs.writeFileSync(path.join(tmp, n), b);
  check('written files read as current', stale(files, tmp).length === 0);
  const edited = render({ ...dicts, fr: { 'a.b': 'Salut' } }, langs);
  // The French file, and the manifest naming the French script's new hash.
  check('an edited string reads as stale', stale(edited, tmp).join() === 'fr.js,scripts.js');
  fs.writeFileSync(path.join(tmp, 'en.js'), files['en.js'].replace(/\n/g, '\r\n'));
  check('CRLF on disk is not stale', !stale(files, tmp).includes('en.js'));
  const pub = renderPublic(dicts, langs);
  const [frName] = Object.keys(pub);
  check('a cached script per language but English', Object.keys(pub).length === 1 && /^fr\.[0-9a-f]{10}\.js$/.test(frName));
  check('the script carries the table', pub[frName].includes('Bonjour') && pub[frName].startsWith('self.__VENT_I18N__='));
  check('the manifest names that script', files['scripts.js'].includes(`/i18n/${frName}`));
  const [editedName] = Object.keys(renderPublic({ ...dicts, fr: { 'a.b': 'Salut' } }, langs));
  check('a changed word changes the name', editedName !== frName);
  fs.writeFileSync(path.join(tmp, 'fr.0000000000.js'), 'old');
  check('an old script is found to remove', leftovers(pub, tmp).includes('fr.0000000000.js'));
  fs.rmSync(tmp, { recursive: true, force: true });
  console.log(`${11 - failed}/11 self-test cases`);
  return failed === 0;
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  if (process.argv.includes('--self-test')) process.exit(selfTest() ? 0 : 1);
  const { dictionaries, languages } = await load(SOURCE);
  const files = render(dictionaries, languages);
  const publicFiles = renderPublic(dictionaries, languages);
  if (process.argv.includes('--check')) {
    const behind = [...stale(files, OUT), ...stale(publicFiles, PUBLIC_OUT).map((n) => `public/i18n/${n}`)];
    if (behind.length) {
      console.log(`generated dictionaries out of date: ${behind.join(', ')}. Run node scripts/split-dictionaries.mjs`);
      process.exit(1);
    }
    console.log(`generated dictionaries current (${Object.keys(files).length + Object.keys(publicFiles).length} files)`);
    process.exit(0);
  }
  fs.mkdirSync(OUT, { recursive: true });
  for (const [name, body] of Object.entries(files)) fs.writeFileSync(path.join(OUT, name), body);
  fs.mkdirSync(PUBLIC_OUT, { recursive: true });
  for (const name of leftovers(publicFiles, PUBLIC_OUT)) fs.rmSync(path.join(PUBLIC_OUT, name));
  for (const [name, body] of Object.entries(publicFiles)) fs.writeFileSync(path.join(PUBLIC_OUT, name), body);
  const sizes = Object.entries({ ...files, ...publicFiles })
    .map(([n, b]) => `${n} ${Math.round(Buffer.byteLength(b) / 1024)} KB`);
  console.log(`wrote ${sizes.join(', ')}`);
}
