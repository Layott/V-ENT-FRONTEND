#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * Put every page-guide string into the English, French and Portuguese
 * dictionaries.
 *
 * The guides are written in English in `pageGuides.js`, which is the source of
 * truth for the words. That file cannot be the dictionary, though: the hard rule
 * is that a user-facing string goes through `t()` with a key that exists in all
 * three languages, and a key present only in English falls back silently, which
 * is the failure nobody ever notices.
 *
 * So the English entries are generated straight from the registry, and the
 * French and Portuguese come from a translation file keyed by the English text.
 * Keying the translations by the English rather than by the route means an
 * identical sentence used on two pages is translated once.
 *
 * Usage: node scripts/write-guide-strings.mjs <translations.json>
 *   where the file is { "<english>": ["<french>", "<portuguese>"], ... }
 */

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { guideStrings } from './guide-keys.mjs';

const HERE = path.dirname(fileURLToPath(import.meta.url));
const DICT = path.join(HERE, '..', 'src', 'i18n', 'dictionaries.js');

const translations = JSON.parse(fs.readFileSync(process.argv[2], 'utf8'));

const pairs = guideStrings();
const missing = pairs.filter(([, en]) => !translations[en]);
if (missing.length) {
  console.log(`NO TRANSLATION FOR ${missing.length} STRINGS:`);
  for (const [key, en] of missing.slice(0, 20)) console.log(`  ${key}  ${en}`);
  process.exit(1);
}

/** A JS single-quoted string literal. */
const lit = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

// The three dictionaries are three object literals in one file. Each is
// anchored on a key that exists in all three, so the block lands inside the
// right one rather than at a line number that shifts.
const ANCHORS = [
  "    'help.whatYouCanDo': 'What you can do here',",
  "    'help.whatYouCanDo': 'Ce que vous pouvez y faire',",
  "    'help.whatYouCanDo': 'O que pode fazer aqui',",
];

let text = fs.readFileSync(DICT, 'utf8');

// Written twice would double every guide string, so clear any previous run.
const START = '    /* --- page guides: generated by scripts/write-guide-strings.mjs --- */\n';
const END = '    /* --- end page guides --- */\n';
while (text.includes(START)) {
  const from = text.indexOf(START);
  const to = text.indexOf(END, from) + END.length;
  text = text.slice(0, from) + text.slice(to);
}

for (let lang = 0; lang < 3; lang += 1) {
  const anchor = ANCHORS[lang];
  const at = text.indexOf(anchor);
  if (at === -1) throw new Error(`anchor not found for language ${lang}: ${anchor}`);
  const block = START
    + pairs.map(([key, en]) => {
      const value = lang === 0 ? en : translations[en][lang - 1];
      return `    ${lit(key)}: ${lit(value)},`;
    }).join('\n')
    + '\n' + END;
  const insertAt = at + anchor.length + 1;
  text = text.slice(0, insertAt) + block + text.slice(insertAt);
}

fs.writeFileSync(DICT, text);

// Read it back and count, rather than trusting the write.
const written = fs.readFileSync(DICT, 'utf8');
let wrong = 0;
for (const [key] of pairs) {
  const n = (written.match(new RegExp(`^ {4}'${key.replace(/\./g, '\\.')}':`, 'gm')) || []).length;
  if (n !== 3) { wrong += 1; if (wrong <= 5) console.log(`  ${key} appears ${n} times`); }
}
if (wrong) {
  console.log(`${wrong} keys are not in all three dictionaries`);
  process.exit(1);
}
console.log(`${pairs.length} guide strings written to en, fr and pt`);
