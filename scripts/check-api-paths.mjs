// Every path the frontend fetches is a path the backend actually serves.
//
// CEO, 7 September 2026: "walk all thefrontend works that have been done."
//
// The walk found `src/lib/money.js` fetching `/auth/settings/`. There is no
// such route. It answered 404 on EVERY page load, inside a `try` whose comment
// says "a failed preference lookup must never be the reason a date does not
// render" - so it failed silently, for ever, and `setAppRegion` never received
// the saved timezone, date format or currency.
//
// The visible symptom was the Currency and region panel storing an answer and
// changing nothing on screen: exactly what that panel had already been
// reported for, one level further up, and still there after it was "fixed".
//
// This is a whole CLASS. A wrong fetch path is invisible in a way a wrong
// import is not:
//
//   * it compiles, lints and type-checks;
//   * the response is a 404 HTML page that `.json()` rejects, so a `catch`
//     swallows it;
//   * the screen renders perfectly, just without the thing it asked for.
//
// So the check is a join: pull every route Django serves, pull every literal
// path the frontend fetches, and report any fetch that matches nothing.
//
//   node scripts/check-api-paths.mjs --routes ../tools/_routes.txt
//   node scripts/check-api-paths.mjs --self-test
//
// The route list is regenerated by tools/dump-routes.py, so this cannot drift
// into checking against a snapshot nobody refreshes.

import fs from 'node:fs';
import path from 'node:path';

const SKIP = new Set(['node_modules', '.next', '.git']);

const walk = (dir, out = []) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (/\.m?jsx?$/.test(entry.name)) out.push(full);
  }
  return out;
};

/**
 * A Django URL pattern as a matcher.
 *
 * `admin/users/<str:user_id>/ban/` becomes a regex where the converter matches
 * anything without a slash. Regex patterns (`^...$`) are taken as written.
 */
export function routeToRegex(pattern) {
  let p = String(pattern);
  if (p.startsWith('^')) {
    // A re_path. Strip the anchors and the named groups down to a wildcard.
    p = p.replace(/^\^/, '').replace(/\$$/, '')
      .replace(/\(\?P<[^>]+>[^)]*\)/g, '[^/]+');
    return new RegExp(`^/?${p}$`);
  }
  const escaped = p
    .replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
    .replace(/<[^>]+>/g, '[^/]+');
  return new RegExp(`^/?${escaped}$`);
}

/**
 * Every literal path the frontend fetches off NEXT_PUBLIC_API_URL.
 *
 * Only the STATIC prefix is taken: `/event/${ref}/slots/` yields
 * `/event/*` + `/slots/`, which is enough to catch a wrong first segment - the
 * fault that actually happens - without trying to evaluate JavaScript.
 */
export function fetchedPaths(src) {
  const out = [];
  const re = /NEXT_PUBLIC_API_URL\}([^`'"]*)/g;
  for (const m of src.matchAll(re)) {
    const raw = m[1];
    if (!raw.startsWith('/')) continue;
    out.push({ raw, index: m.index });
  }
  return out;
}

/**
 * A fetched path with no template holes at all can be checked exactly.
 *
 * A BASE-URL helper is not a fetch and must not be treated as one:
 *
 *     const base = () => `${process.env.NEXT_PUBLIC_API_URL}/tournament`;
 *
 * That is a prefix somebody appends to, and reporting it says a real route is
 * missing when nothing is. A path with no trailing slash is never a Django
 * route here - every one of the 643 ends in `/` - so the absence of one is
 * exactly the signal that this is a prefix rather than an address.
 */
const isLiteral = (p) => !p.includes('$') && !p.includes('{') && p.endsWith('/');

export function findings(files, routes) {
  const matchers = routes.map(routeToRegex);
  const hits = [];
  for (const { rel, src } of files) {
    const clean = src.replace(/\/\*[\s\S]*?\*\//g, '');
    for (const { raw, index } of fetchedPaths(clean)) {
      if (!isLiteral(raw)) continue;
      const trimmed = raw.split('?')[0];
      if (matchers.some((m) => m.test(trimmed))) continue;
      hits.push({
        rel,
        line: clean.slice(0, index).split('\n').length,
        path: trimmed,
      });
    }
  }
  return hits;
}

const SELF_TEST = [
  {
    why: 'the real fault: /auth/settings/ is served by nothing',
    flag: true,
    src: 'const res = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/auth/settings/`);',
    routes: ['setting/', 'auth/login/'],
  },
  {
    why: 'the corrected path',
    flag: false,
    src: 'const res = await fetch(`${process.env.NEXT_PUBLIC_API_URL}/setting/`);',
    routes: ['setting/', 'auth/login/'],
  },
  {
    why: 'a path with a converter in the route still matches',
    flag: false,
    src: 'fetch(`${process.env.NEXT_PUBLIC_API_URL}/auth/admin/users/`)',
    routes: ['auth/admin/users/', 'auth/admin/users/<str:user_id>/'],
  },
  {
    why: 'an interpolated path is skipped rather than guessed at',
    flag: false,
    src: 'fetch(`${process.env.NEXT_PUBLIC_API_URL}/event/${ref}/slots/`)',
    routes: ['event/<str:event_id>/slots/'],
  },
  {
    why: 'a query string does not stop a literal path matching',
    flag: false,
    src: 'fetch(`${process.env.NEXT_PUBLIC_API_URL}/setting/?full=1`)',
    routes: ['setting/'],
  },
  {
    why: 'a base-URL helper is a prefix, not an address',
    flag: false,
    src: 'const base = () => `${process.env.NEXT_PUBLIC_API_URL}/tournament`;',
    routes: ['tournament/<int:id>/requirements/mine/'],
  },
  {
    why: 'a typo in a real path is still caught',
    flag: true,
    src: 'fetch(`${process.env.NEXT_PUBLIC_API_URL}/settings/`)',
    routes: ['setting/'],
  },
];

if (process.argv.includes('--self-test')) {
  let bad = 0;
  for (const c of SELF_TEST) {
    const got = findings([{ rel: 'x.js', src: c.src }], c.routes).length > 0;
    if (got !== c.flag) {
      bad += 1;
      console.log(`FAIL  expected ${c.flag ? 'a finding' : 'no finding'}: ${c.why}`);
    }
  }
  if (bad) {
    console.log(`${bad} of ${SELF_TEST.length} case(s) wrong`);
    process.exit(1);
  }
  console.log(`${SELF_TEST.length} cases, both directions: self-test passed`);
  process.exit(0);
}

const at = process.argv.indexOf('--routes');
const routesFile = at === -1
  ? path.join(process.cwd(), '..', 'tools', '_routes.txt')
  : process.argv[at + 1];

let routes;
try {
  routes = fs.readFileSync(routesFile, 'utf8').split('\n').map((r) => r.trim()).filter(Boolean);
} catch {
  console.log(`Could not read ${routesFile}.`);
  console.log('Regenerate it: python tools/dump-routes.py');
  process.exit(1);
}

const files = walk('src').map((f) => ({
  rel: f.split(path.sep).join('/'),
  src: fs.readFileSync(f, 'utf8'),
}));

const hits = findings(files, routes);
for (const h of hits) {
  console.log(`${h.rel}:${h.line}  ${h.path}`);
  console.log('  nothing in the backend serves this path, so the fetch is a 404');
  console.log('');
}
console.log(`${routes.length} route(s) checked, ${hits.length} fetch(es) that go nowhere`);
process.exit(hits.length ? 1 : 0);
